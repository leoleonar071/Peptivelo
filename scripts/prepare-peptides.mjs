import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const read = (path) => JSON.parse(readFileSync(resolve(root, path), "utf8"));
// Same canonical serialization as publication-policy; parity is tested.
export function revision(value) {
  if (Array.isArray(value)) return `[${value.map(revision).join(",")}]`;
  if (value !== null && typeof value === "object")
    return `{${Object.entries(value)
      .filter(([, v]) => v !== undefined)
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
      .map(([k, v]) => `${JSON.stringify(k)}:${revision(v)}`)
      .join(",")}}`;
  return JSON.stringify(value) ?? "null";
}
export function preparePublicPeptides(records, reviews) {
  return records.filter(
    (p) =>
      !p.existingDocumentId &&
      p.status === "published" &&
      ["editorial", "scientific"].every((kind) =>
        reviews.some(
          (review) =>
            review.documentId === p.id &&
            review.revision === revision(p) &&
            review.kind === kind &&
            /^[a-z][a-z0-9-]{2,63}$/.test(review.reviewerId) &&
            /^\d{4}-\d{2}-\d{2}$/.test(review.reviewedAt),
        ),
      ),
  );
}
// The browser receives the existing public label catalog, never editorial
// comparisons or image permission records.
export function projectPublicCatalog(catalog) {
  const products = catalog.products
    .filter((product) => product.editorialStatus === "published")
    .map((product) => {
      const publicProduct = { ...product };
      delete publicProduct.editorialImages;
      return publicProduct;
    });
  const ingredients = catalog.ingredients.filter(
    (ingredient) => ingredient.status === "published",
  );
  const prices = catalog.prices.filter((price) =>
    products.some((p) => p.id === price.productId),
  );
  const sourceIds = new Set(["fda-cosmetic-reactions"]);
  for (const product of products) sourceIds.add(product.sourceId);
  for (const price of prices) sourceIds.add(price.sourceId);
  for (const ingredient of ingredients) {
    for (const id of ingredient.sourceIds) sourceIds.add(id);
    for (const section of Object.values(ingredient.education)) {
      for (const id of section?.sourceIds ?? []) sourceIds.add(id);
    }
  }
  return {
    products,
    ingredients,
    prices,
    brands: catalog.brands.filter((brand) =>
      products.some((p) => p.brandId === brand.id),
    ),
    retailers: catalog.retailers.filter((retailer) =>
      prices.some((p) => p.retailerId === retailer.id),
    ),
    sources: catalog.sources.filter((source) => sourceIds.has(source.id)),
  };
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const files = readdirSync(resolve(root, "src/data/peptides"))
    .filter((name) => name.endsWith(".json"))
    .sort();
  const records = files.map((name) => read(`src/data/peptides/${name}`));
  const imports = files
    .map(
      (name, index) => `import record${index} from "../data/peptides/${name}";`,
    )
    .join("\n");
  writeFileSync(
    resolve(root, "src/lib/peptide-records.ts"),
    `// Generated by npm run editorial:prepare. Server editorial records only.\nimport "server-only";\n${imports}\nimport { peptideSchema } from "./peptide-schema";\nexport const peptideRecords = [${files.map((_, index) => `record${index}`).join(", ")}].map((record) => peptideSchema.parse(record));\n`,
  );
  const catalog = read("src/data/catalog.json");
  const scalpSvg = readFileSync(
    resolve(root, "src/data/private-assets/ordinary-hair-density.svg"),
    "utf8",
  );
  writeFileSync(
    resolve(root, "src/lib/scalp-record-image.ts"),
    `// Generated by npm run editorial:prepare from the private scalp record.\nimport "server-only";\nexport const scalpRecordImage = ${JSON.stringify(scalpSvg)};\n`,
  );
  const publicCatalog = projectPublicCatalog(catalog);
  const writeProjection = (name, value) =>
    writeFileSync(
      resolve(root, `src/data/${name}.json`),
      JSON.stringify(value, null, 2) + "\n",
    );
  writeProjection("public-catalog", publicCatalog);
  writeProjection(
    "public-offers",
    read("src/data/offers.json").filter((offer) =>
      publicCatalog.products.some((product) => product.id === offer.productId),
    ),
  );
  writeProjection("public-navigation", {
    productReturnPaths: publicCatalog.products.map(
      (product) => `/skincare/products/${product.slug}/`,
    ),
  });
  const bindings = new Map(
    catalog.ingredients.map((i) => [
      `skin:${i.id}`,
      `/skincare/ingredients/${i.slug}/`,
    ]),
  );
  bindings.set("library:bpc-157", "/library/bpc-157/");
  bindings.set("library:retatrutide", "/library/retatrutide/");
  for (const p of records)
    if (
      p.existingDocumentId &&
      bindings.get(p.existingDocumentId) !== p.canonicalPath
    )
      throw new Error(`Invalid existing canonical binding: ${p.id}`);
  const output = preparePublicPeptides(
    records,
    read("src/data/publication-reviews.json"),
  );
  writeFileSync(
    resolve(root, "src/data/public-peptides.json"),
    JSON.stringify(output, null, 2) + "\n",
  );
  console.log(
    `Prepared ${output.length} reviewed public peptide records; ${records.length} editorial records retained.`,
  );
}
