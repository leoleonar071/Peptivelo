import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const read = (path) => JSON.parse(readFileSync(resolve(root, path), "utf8"));
// Same canonical serialization as publication-policy; parity is tested.
export function revision(value) {
  if (Array.isArray(value)) return `[${value.map(revision).join(",")}]`;
  if (value !== null && typeof value === "object")
    return `{${Object.entries(value)
      .filter(([, v]) => v !== undefined)
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
      .map(([k, v]) => `${JSON.stringify(k)}:${revision(v)}`)
      .join(",")}}`;
  return JSON.stringify(value) ?? "null";
}
export function preparePublicPeptides(records, reviews) {
  return records.filter(
    (p) =>
      !p.existingDocumentId &&
      p.status === "published" &&
      ["editorial", "scientific"].every((kind) =>
        reviews.some(
          (review) =>
            review.documentId === p.id &&
            review.revision === revision(p) &&
            review.kind === kind &&
            /^[a-z][a-z0-9-]{2,63}$/.test(review.reviewerId) &&
            /^\d{4}-\d{2}-\d{2}$/.test(review.reviewedAt),
        ),
      ),
  );
}
if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const files = readdirSync(resolve(root, "src/data/peptides"))
    .filter((name) => name.endsWith(".json"))
    .sort();
  const records = files.map((name) => read(`src/data/peptides/${name}`));
  const imports = files
    .map(
      (name, index) => `import record${index} from "../data/peptides/${name}";`,
    )
    .join("\n");
  writeFileSync(
    resolve(root, "src/lib/peptide-records.ts"),
    `// Generated by npm run editorial:prepare. Server editorial records only.\n${imports}\nimport { peptideSchema } from "./peptide-schema";\nexport const peptideRecords = [${files.map((_, index) => `record${index}`).join(", ")}].map((record) => peptideSchema.parse(record));\n`,
  );
  const catalog = read("src/data/catalog.json");
  const bindings = new Map(
    catalog.ingredients.map((i) => [
      `skin:${i.id}`,
      `/skincare/ingredients/${i.slug}/`,
    ]),
  );
  bindings.set("library:bpc-157", "/library/bpc-157/");
  bindings.set("library:retatrutide", "/library/retatrutide/");
  for (const p of records)
    if (
      p.existingDocumentId &&
      bindings.get(p.existingDocumentId) !== p.canonicalPath
    )
      throw new Error(`Invalid existing canonical binding: ${p.id}`);
  const output = preparePublicPeptides(
    records,
    read("src/data/publication-reviews.json"),
  );
  writeFileSync(
    resolve(root, "src/data/public-peptides.json"),
    JSON.stringify(output, null, 2) + "\n",
  );
  console.log(
    `Prepared ${output.length} reviewed public peptide records; ${records.length} editorial records retained.`,
  );
}
